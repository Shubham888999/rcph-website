// The greeting line is the note's first paragraph; the card shows the start of the note after it.
export function notePreview(note, max = 140) {
  const body = note.paragraphs.slice(1).join(" ") || note.paragraphs[0] || "";
  return body.length > max ? `${body.slice(0, max).replace(/\s+\S*$/, "")}…` : body;
}
